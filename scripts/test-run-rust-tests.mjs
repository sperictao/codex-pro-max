import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import test from "node:test";

const runner = fileURLToPath(new URL("./run-rust-tests.mjs", import.meta.url));

function createFixture() {
  const root = mkdtempSync(join(tmpdir(), "dashi-rust-runner-"));
  mkdirSync(join(root, "src"), { recursive: true });
  writeFileSync(
    join(root, "Cargo.toml"),
    '[package]\nname = "runner-fixture"\nversion = "0.1.0"\nedition = "2021"\n',
  );
  writeFileSync(
    join(root, "Cargo.lock"),
    '# This file is automatically @generated by Cargo.\nversion = 3\n\n[[package]]\nname = "runner-fixture"\nversion = "0.1.0"\n',
  );
  writeFileSync(
    join(root, "src", "lib.rs"),
    `#[cfg(test)]
mod tests {
    #[test]
    fn sees_disposable_home() {
        let home = std::env::var("HOME").unwrap();
        let profile = std::env::var("USERPROFILE").unwrap();
        assert_eq!(home, profile);
        assert_ne!(home, std::env::var("DASHI_REAL_HOME").unwrap());
        assert_eq!(std::env::var("CARGO_HOME").unwrap(), std::env::var("DASHI_EXPECTED_CARGO_HOME").unwrap());
        assert_eq!(std::env::var("RUSTUP_HOME").unwrap(), std::env::var("DASHI_EXPECTED_RUSTUP_HOME").unwrap());
    }

    #[test]
    fn times_out() {
        std::thread::sleep(std::time::Duration::from_secs(10));
    }
}
`,
  );
  return root;
}

function runRunner(root, args) {
  const realHome = homedir();
  const cargoHome = process.env.CARGO_HOME ?? join(realHome, ".cargo");
  const rustupHome = process.env.RUSTUP_HOME ?? join(realHome, ".rustup");
  return spawnSync(
    process.execPath,
    [runner, "--manifest-path", join(root, "Cargo.toml"), ...args],
    {
      encoding: "utf8",
      env: {
        ...process.env,
        DASHI_REAL_HOME: realHome,
        DASHI_EXPECTED_CARGO_HOME: cargoHome,
        DASHI_EXPECTED_RUSTUP_HOME: rustupHome,
      },
    },
  );
}

test("Rust runner rejects filters that match zero tests", () => {
  const root = createFixture();
  try {
    const result = runRunner(root, ["--filter", "tests::__missing__", "--timeout", "5"]);
    assert.equal(result.status, 2, result.stderr || result.stdout);
    assert.match(result.stderr, /matched zero tests/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("Rust runner isolates home while preserving toolchain homes", () => {
  const root = createFixture();
  try {
    const result = runRunner(root, [
      "--filter",
      "tests::sees_disposable_home",
      "--timeout",
      "5",
    ]);
    assert.equal(result.status, 0, result.stderr || result.stdout);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("Rust runner returns 124 when the execution phase times out", () => {
  const root = createFixture();
  try {
    const result = runRunner(root, ["--filter", "tests::times_out", "--timeout", "1"]);
    assert.equal(result.status, 124, result.stderr || result.stdout);
    assert.match(result.stderr, /timed out after 1 second/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
